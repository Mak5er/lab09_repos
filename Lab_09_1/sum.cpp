using namespace nsDod;
using namespace nsVar;

// Обчислення суми ряду Тейлора для e^(x^2) з точністю e
void nsSum::sum()
{
    n = 0;      // початковий індекс доданку
    a = 1.0;    // нульовий доданок ряду a_0 = x^0 / 0! = 1
    s = a;      // початкове значення суми

    do
    {
        n++;
        dod();  // обчислення чергового доданку через рекурентне співвідношення
        s += a;
    } while (std::fabs(a) > e && n < 100000);
}
